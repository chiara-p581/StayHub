BEGIN;

CREATE TABLE IF NOT EXISTS limite_solicitud (
    clave VARCHAR(180) PRIMARY KEY,
    ventana_inicio BIGINT NOT NULL,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    expira_en BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_limite_solicitud_expira ON limite_solicitud(expira_en);

CREATE TABLE IF NOT EXISTS evento_auditoria_seguridad (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    correlation_id VARCHAR(64) NOT NULL,
    actor_id VARCHAR(80) NOT NULL,
    rol VARCHAR(20) NOT NULL,
    accion VARCHAR(64) NOT NULL,
    resultado VARCHAR(20) NOT NULL,
    recurso VARCHAR(180) NOT NULL,
    origen_hash VARCHAR(32) NOT NULL,
    detalle VARCHAR(180) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_auditoria_fecha ON evento_auditoria_seguridad(fecha DESC);
CREATE INDEX IF NOT EXISTS ix_auditoria_correlacion ON evento_auditoria_seguridad(correlation_id);
CREATE INDEX IF NOT EXISTS ix_auditoria_actor ON evento_auditoria_seguridad(actor_id, fecha DESC);

COMMIT;
