-- Esquema base reproducible de StayHub para PostgreSQL.
-- Debe mantenerse alineado con las entidades JPA; WildFly valida el esquema al desplegar.

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(120) NOT NULL UNIQUE,
    password_hash VARCHAR(200) NOT NULL,
    nombre VARCHAR(80) NOT NULL,
    apellido VARCHAR(80) NOT NULL,
    rol VARCHAR(20) NOT NULL CHECK (rol IN ('HUESPED', 'ADMIN')),
    reset_token_hash VARCHAR(64) UNIQUE,
    reset_token_vencimiento TIMESTAMP(6),
    version BIGINT
);

CREATE TABLE hotel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    direccion VARCHAR(180) NOT NULL,
    ciudad VARCHAR(100) NOT NULL,
    pais VARCHAR(100) NOT NULL,
    descripcion VARCHAR(1000),
    activo BOOLEAN NOT NULL
);

CREATE TABLE hotel_servicio (
    hotel_id BIGINT NOT NULL REFERENCES hotel(id) ON DELETE CASCADE,
    servicio VARCHAR(80) NOT NULL
);

CREATE TABLE tipo_habitacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id BIGINT NOT NULL REFERENCES hotel(id),
    codigo VARCHAR(30) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(800),
    capacidad_maxima INTEGER NOT NULL CHECK (capacidad_maxima > 0),
    activo BOOLEAN NOT NULL,
    CONSTRAINT uk_tipo_hotel_codigo UNIQUE (hotel_id, codigo)
);

CREATE TABLE tipo_habitacion_caracteristica (
    tipo_habitacion_id BIGINT NOT NULL REFERENCES tipo_habitacion(id) ON DELETE CASCADE,
    caracteristica VARCHAR(100) NOT NULL
);

CREATE TABLE habitacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id BIGINT NOT NULL REFERENCES hotel(id),
    tipo_habitacion_id BIGINT NOT NULL REFERENCES tipo_habitacion(id),
    numero VARCHAR(30) NOT NULL,
    piso INTEGER,
    activa BOOLEAN NOT NULL,
    CONSTRAINT uk_habitacion_hotel_numero UNIQUE (hotel_id, numero)
);

CREATE TABLE habitacion_caracteristica (
    habitacion_id BIGINT NOT NULL REFERENCES habitacion(id) ON DELETE CASCADE,
    caracteristica VARCHAR(100) NOT NULL
);

CREATE TABLE inventario_diario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id BIGINT NOT NULL,
    tipo_habitacion VARCHAR(30) NOT NULL,
    fecha DATE NOT NULL,
    unidades_totales INTEGER NOT NULL CHECK (unidades_totales >= 0),
    unidades_ocupadas INTEGER NOT NULL CHECK (unidades_ocupadas >= 0 AND unidades_ocupadas <= unidades_totales),
    precio NUMERIC(12,2) NOT NULL CHECK (precio >= 0),
    moneda VARCHAR(3) NOT NULL CHECK (moneda ~ '^[A-Z]{3}$'),
    version BIGINT,
    CONSTRAINT uk_hotel_tipo_fecha UNIQUE (hotel_id, tipo_habitacion, fecha)
);

CREATE TABLE hold_disponibilidad (
    id VARCHAR(36) PRIMARY KEY,
    hotel_id BIGINT NOT NULL,
    tipo_habitacion VARCHAR(30) NOT NULL,
    cantidad_habitaciones INTEGER NOT NULL CHECK (cantidad_habitaciones > 0),
    check_in DATE NOT NULL,
    check_out DATE NOT NULL,
    estado VARCHAR(20) NOT NULL,
    fecha_creacion TIMESTAMP(6) NOT NULL,
    fecha_actualizacion TIMESTAMP(6),
    CHECK (check_out > check_in)
);

CREATE TABLE reserva (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canal VARCHAR(30) NOT NULL,
    referencia_externa VARCHAR(60),
    usuario_id BIGINT REFERENCES usuario(id),
    hotel_id BIGINT NOT NULL,
    tipo_habitacion VARCHAR(30) NOT NULL,
    cantidad_habitaciones INTEGER NOT NULL CHECK (cantidad_habitaciones > 0),
    check_in DATE NOT NULL,
    check_out DATE NOT NULL,
    nombre VARCHAR(80) NOT NULL,
    apellido VARCHAR(80) NOT NULL,
    email VARCHAR(120) NOT NULL,
    telefono VARCHAR(30),
    precio_total NUMERIC(12,2) NOT NULL CHECK (precio_total >= 0),
    moneda VARCHAR(3) NOT NULL CHECK (moneda ~ '^[A-Z]{3}$'),
    hold_id VARCHAR(60),
    estado VARCHAR(20) NOT NULL,
    fecha_creacion TIMESTAMP(6) NOT NULL,
    fecha_actualizacion TIMESTAMP(6),
    version BIGINT,
    CONSTRAINT uk_canal_referencia_externa UNIQUE (canal, referencia_externa),
    CHECK (check_out > check_in)
);

CREATE INDEX ix_reserva_usuario_estado ON reserva(usuario_id, estado, id);
CREATE INDEX ix_reserva_usuario_listado ON reserva(usuario_id, id DESC);
CREATE INDEX ix_reserva_hotel_listado ON reserva(hotel_id, id DESC);
CREATE INDEX ix_reserva_llegadas ON reserva(hotel_id, check_in, estado, id);
CREATE INDEX ix_reserva_pendiente_expira ON reserva(fecha_creacion, id)
    WHERE estado = 'PENDIENTE' AND usuario_id IS NOT NULL;

CREATE TABLE pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    monto NUMERIC(12,2) NOT NULL CHECK (monto > 0),
    moneda VARCHAR(3) NOT NULL CHECK (moneda ~ '^[A-Z]{3}$'),
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('PENDIENTE', 'APROBADO', 'RECHAZADO')),
    referencia_pasarela VARCHAR(60),
    fecha_pago TIMESTAMP(6) NOT NULL,
    clave_idempotencia VARCHAR(80),
    version BIGINT,
    CONSTRAINT uk_pago_usuario_idempotencia UNIQUE (usuario_id, clave_idempotencia)
);

CREATE TABLE pago_reserva (
    pago_id BIGINT NOT NULL REFERENCES pago(id) ON DELETE CASCADE,
    reserva_id BIGINT NOT NULL,
    CONSTRAINT uk_pago_reserva_item UNIQUE (pago_id, reserva_id)
);

CREATE INDEX ix_pago_usuario_fecha ON pago(usuario_id, fecha_pago DESC);
CREATE INDEX ix_pago_reserva_estado ON pago(reserva_id, estado);

CREATE TABLE conflicto_overbooking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id_conflictiva BIGINT NOT NULL,
    hotel_id BIGINT NOT NULL,
    tipo_habitacion VARCHAR(30) NOT NULL,
    cantidad_habitaciones INTEGER NOT NULL CHECK (cantidad_habitaciones > 0),
    check_in DATE NOT NULL,
    check_out DATE NOT NULL,
    canal_origen VARCHAR(30),
    referencia_externa VARCHAR(60),
    huesped_email VARCHAR(120),
    estrategia_aplicada VARCHAR(30),
    resuelto BOOLEAN NOT NULL,
    hold_alternativo_id VARCHAR(60),
    tipo_habitacion_alternativa VARCHAR(30),
    mensaje VARCHAR(255),
    fecha_creacion TIMESTAMP(6) NOT NULL
);

CREATE TABLE notificacion_email_enviada (
    clave VARCHAR(180) PRIMARY KEY,
    fecha TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
